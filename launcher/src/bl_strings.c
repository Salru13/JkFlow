const char *bl_str(BlStringId id)
{
    if ((int)id < 0 || id >= BL_S_COUNT || !STRINGS[id]) return "";
    return STRINGS[id];
}

const char *bl_str_n(BlStringId one, BlStringId many, long long n)
{
    return bl_str(n == 1 ? one : many);
}
