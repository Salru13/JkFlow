"""Build-time tool: crop BLUR's own wordmark (tools/make_art.c, with its glow) out of the
package icon and write it as packed RGB C source for bl_ui.

    python3 -I bake_logo.py ICON0.png OUT.c

Uses only the standard library (zlib) to read the PNG. The crop matches the
one the current start page uses (blur-launcher-266/prepare.py LOGO_CROP).
"""
import struct
import sys
import zlib

LOGO_CROP = (50, 150, 412, 212)  # x, y, width, height: the wordmark of tools/make_art.c (logo.png) with its glow


def read_png(path):
    data = open(path, 'rb').read()
    if data[:8] != b'\x89PNG\r\n\x1a\n':
        raise SystemExit('bake_logo: not a PNG: %s' % path)
    pos, idat, ihdr = 8, b'', None
    while pos < len(data):
        length, kind = struct.unpack('>I4s', data[pos:pos + 8])
        body = data[pos + 8:pos + 8 + length]
        if kind == b'IHDR':
            ihdr = struct.unpack('>IIBBBBB', body)
        elif kind == b'IDAT':
            idat += body
        elif kind == b'IEND':
            break
        pos += 12 + length
    width, height, depth, ctype, _comp, _filt, interlace = ihdr
    if depth != 8 or ctype not in (2, 6) or interlace:
        raise SystemExit('bake_logo: need 8-bit RGB/RGBA non-interlaced PNG')
    bpp = 3 if ctype == 2 else 4
    raw = zlib.decompress(idat)
    stride = width * bpp
    rows, prev = [], bytearray(stride)
    for y in range(height):
        f = raw[y * (stride + 1)]
        line = bytearray(raw[y * (stride + 1) + 1:(y + 1) * (stride + 1)])
        for i in range(stride):
            a = line[i - bpp] if i >= bpp else 0
            b = prev[i]
            c = prev[i - bpp] if i >= bpp else 0
            if f == 1:
                line[i] = (line[i] + a) & 255
            elif f == 2:
                line[i] = (line[i] + b) & 255
            elif f == 3:
                line[i] = (line[i] + ((a + b) >> 1)) & 255
            elif f == 4:
                p = a + b - c
                pa, pb, pc = abs(p - a), abs(p - b), abs(p - c)
                pr = a if pa <= pb and pa <= pc else (b if pb <= pc else c)
                line[i] = (line[i] + pr) & 255
            elif f != 0:
                raise SystemExit('bake_logo: bad filter %d' % f)
        rows.append(bytes(line) if bpp == 3 else bytes(v for i, v in enumerate(line) if i % 4 != 3))
        prev = line
    return width, height, rows


def main():
    if len(sys.argv) != 3:
        raise SystemExit('usage: bake_logo.py ICON0.png OUT.c')
    width, height, rows = read_png(sys.argv[1])
    x0, y0, w, h = LOGO_CROP
    if x0 + w > width or y0 + h > height:
        raise SystemExit('bake_logo: crop outside the %dx%d icon' % (width, height))
    # Feather the crop border so the cut-off glow leaves no visible edge
    # when the logo is drawn additively and enlarged.
    feather = 14
    out_px = bytearray()
    for yy in range(h):
        row = rows[y0 + yy]
        fy = min(yy, h - 1 - yy, feather) / feather
        for xx in range(w):
            k = min(fy, min(xx, w - 1 - xx, feather) / feather)
            k = k * k * (3 - 2 * k)
            for ch in range(3):
                out_px.append(int(row[(x0 + xx) * 3 + ch] * k + 0.5))
    pixels = bytes(out_px)
    out = ['/* Generated by launcher/tools/bake_logo.py from the package icon. Do not edit. */',
           '#include <stdint.h>',
           'const int bl_logo_w = %d, bl_logo_h = %d;' % (w, h),
           'const uint8_t bl_logo_rgb[] = {']
    for i in range(0, len(pixels), 36):
        out.append(','.join(str(v) for v in pixels[i:i + 36]) + ',')
    out.append('};')
    open(sys.argv[2], 'w').write('\n'.join(out) + '\n')


if __name__ == '__main__':
    main()
