/*
 * Build-time tool: render the launcher's Nunito styles into 8-bit alpha
 * glyph atlases and write them as C source.
 *
 *   bake_font REGULAR_VF.ttf ITALIC_VF.ttf OUT.h OUT.c
 *
 * Nunito ships as variable fonts; the weight axis selects Black (900) or
 * ExtraBold (800). The order of STYLES must match enum BlFont in bl_ui.h.
 */
#include <ft2build.h>
#include FT_FREETYPE_H
#include FT_MULTIPLE_MASTERS_H

#include <stddef.h>
#include <stdint.h>
#include <stdio.h>
#include <stdlib.h>

typedef struct { const char *name; int size, weight, italic; } Style;
static const Style STYLES[] = {
    { "NOTE",  22, 800, 0 },
    { "BODY",  28, 800, 0 },
    { "ITEM",  34, 900, 0 },
    { "HEAD",  40, 900, 0 },
    { "TITLE", 70, 900, 0 },
    { "BAND",  32, 800, 1 },
};
#define NSTYLES (int)(sizeof STYLES / sizeof STYLES[0])

/* Sorted ascending: the renderer binary-searches this order. */
static uint32_t *codepoints(int *count)
{
    static const uint32_t extra[] = { 0xB7, 0xD7, 0x2014, 0x2019, 0x2022, 0x2026, 0x203A };
    int n = 0;
    uint32_t *cps = malloc(sizeof(uint32_t) * (95 + sizeof extra / sizeof extra[0]));
    for (uint32_t c = 32; c <= 126; c++) cps[n++] = c;
    for (size_t i = 0; i < sizeof extra / sizeof extra[0]; i++) cps[n++] = extra[i];
    *count = n;
    return cps;
}

static void die(const char *what, int err)
{
    fprintf(stderr, "bake_font: %s failed (FreeType error %d)\n", what, err);
    exit(1);
}

int main(int argc, char **argv)
{
    if (argc != 5) {
        fprintf(stderr, "usage: bake_font REGULAR_VF.ttf ITALIC_VF.ttf OUT.h OUT.c\n");
        return 2;
    }
    FT_Library lib;
    int err = FT_Init_FreeType(&lib);
    if (err) die("FT_Init_FreeType", err);

    FILE *h = fopen(argv[3], "w"), *c = fopen(argv[4], "w");
    if (!h || !c) { perror("bake_font: open output"); return 1; }

    fprintf(h, "/* Generated by launcher/tools/bake_font.c from Nunito (SIL OFL 1.1). Do not edit. */\n"
               "#ifndef BL_FONT_H\n#define BL_FONT_H\n#include <stdint.h>\n"
               "typedef struct BlGlyph { uint32_t cp; int16_t left, top; uint16_t w, h; int16_t adv; uint32_t off; } BlGlyph;\n"
               "typedef struct BlFontData { int16_t size, ascent, descent, line_h; uint16_t count;\n"
               "    const BlGlyph *glyphs; const uint8_t *alpha; } BlFontData;\n"
               "#define BL_FONT_DATA_COUNT %d\n"
               "extern const BlFontData bl_font_data[BL_FONT_DATA_COUNT];\n#endif\n", NSTYLES);
    fprintf(c, "/* Generated by launcher/tools/bake_font.c from Nunito (SIL OFL 1.1). Do not edit. */\n"
               "#include \"bl_font.h\"\n");

    int ncp;
    uint32_t *cps = codepoints(&ncp);
    int asc[NSTYLES], desc[NSTYLES], lh[NSTYLES], count[NSTYLES];

    for (int s = 0; s < NSTYLES; s++) {
        const Style *st = &STYLES[s];
        FT_Face face;
        err = FT_New_Face(lib, st->italic ? argv[2] : argv[1], 0, &face);
        if (err) die("FT_New_Face", err);
        FT_MM_Var *mm = NULL;
        err = FT_Get_MM_Var(face, &mm);
        if (err) die("FT_Get_MM_Var (font is not variable?)", err);
        FT_Fixed coords[8] = { 0 };
        if (mm->num_axis > 8) die("too many axes", 0);
        for (FT_UInt a = 0; a < mm->num_axis; a++) {
            coords[a] = mm->axis[a].def;
            if (mm->axis[a].tag == FT_MAKE_TAG('w', 'g', 'h', 't')) coords[a] = (FT_Fixed)st->weight << 16;
        }
        err = FT_Set_Var_Design_Coordinates(face, mm->num_axis, coords);
        if (err) die("FT_Set_Var_Design_Coordinates", err);
        FT_Done_MM_Var(lib, mm);
        err = FT_Set_Pixel_Sizes(face, 0, (FT_UInt)st->size);
        if (err) die("FT_Set_Pixel_Sizes", err);

        asc[s] = (int)((face->size->metrics.ascender + 32) >> 6);
        desc[s] = (int)((-face->size->metrics.descender + 32) >> 6);
        lh[s] = (int)((face->size->metrics.height + 32) >> 6);

        fprintf(c, "static const uint8_t alpha_%s[] = {\n", st->name);
        typedef struct { uint32_t cp; int left, top, w, h, adv; unsigned off; } G;
        G *gs = calloc((size_t)ncp, sizeof(G));
        unsigned off = 0, col = 0;
        int n = 0;
        for (int i = 0; i < ncp; i++) {
            FT_UInt gi = FT_Get_Char_Index(face, cps[i]);
            if (!gi && cps[i] != 32) {
                fprintf(stderr, "bake_font: %s: no glyph for U+%04X, skipped\n", st->name, cps[i]);
                continue;
            }
            err = FT_Load_Glyph(face, gi, FT_LOAD_RENDER | FT_LOAD_TARGET_NORMAL);
            if (err) die("FT_Load_Glyph", err);
            FT_GlyphSlot g = face->glyph;
            if (g->bitmap.pixel_mode != FT_PIXEL_MODE_GRAY && g->bitmap.rows) die("unexpected pixel mode", 0);
            G *o = &gs[n++];
            o->cp = cps[i]; o->left = g->bitmap_left; o->top = g->bitmap_top;
            o->w = (int)g->bitmap.width; o->h = (int)g->bitmap.rows;
            o->adv = (int)((g->advance.x + 32) >> 6); o->off = off;
            for (int y = 0; y < o->h; y++) {
                const unsigned char *row = g->bitmap.buffer + (ptrdiff_t)y * g->bitmap.pitch;
                for (int x = 0; x < o->w; x++) {
                    fprintf(c, "%u,", row[x]);
                    if (++col == 32) { fputc('\n', c); col = 0; }
                }
            }
            off += (unsigned)(o->w * o->h);
        }
        fprintf(c, "0};\nstatic const BlGlyph glyphs_%s[] = {\n", st->name);
        for (int i = 0; i < n; i++)
            fprintf(c, "{0x%X,%d,%d,%d,%d,%d,%u},\n", gs[i].cp, gs[i].left, gs[i].top, gs[i].w, gs[i].h, gs[i].adv, gs[i].off);
        fprintf(c, "};\n");
        count[s] = n;
        free(gs);
        FT_Done_Face(face);
    }

    fprintf(c, "const BlFontData bl_font_data[BL_FONT_DATA_COUNT] = {\n");
    for (int s = 0; s < NSTYLES; s++)
        fprintf(c, "{%d,%d,%d,%d,%d,glyphs_%s,alpha_%s},\n", STYLES[s].size, asc[s], desc[s], lh[s],
                count[s], STYLES[s].name, STYLES[s].name);
    fprintf(c, "};\n");
    free(cps);
    fclose(h); fclose(c);
    FT_Done_FreeType(lib);
    return 0;
}
